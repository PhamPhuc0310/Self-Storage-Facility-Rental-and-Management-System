/* Run this first only if dbo.SUPPORT_REQUESTS does not already exist. */
IF OBJECT_ID(N'dbo.SUPPORT_REQUESTS', N'U') IS NULL
BEGIN
 CREATE TABLE dbo.SUPPORT_REQUESTS (
  request_id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_SUPPORT_REQUESTS_id DEFAULT NEWSEQUENTIALID(),
  contract_id UNIQUEIDENTIFIER NOT NULL,
  requested_by UNIQUEIDENTIFIER NOT NULL,
  assigned_staff_id UNIQUEIDENTIFIER NULL,
  request_type NVARCHAR(30) NOT NULL,
  title NVARCHAR(255) NOT NULL,
  description NVARCHAR(MAX) NOT NULL,
  priority NVARCHAR(20) NOT NULL,
  status NVARCHAR(30) NOT NULL,
  created_at DATETIME2 NOT NULL CONSTRAINT DF_SUPPORT_REQUESTS_created_at DEFAULT SYSDATETIME(),
  resolved_at DATETIME2 NULL,
  resolution_note NVARCHAR(MAX) NULL,
  CONSTRAINT PK_SUPPORT_REQUESTS PRIMARY KEY(request_id),
  CONSTRAINT FK_SUPPORT_REQUESTS_CONTRACTS FOREIGN KEY(contract_id) REFERENCES dbo.RENTAL_CONTRACTS(contract_id),
  CONSTRAINT FK_SUPPORT_REQUESTS_REQUESTED_BY FOREIGN KEY(requested_by) REFERENCES dbo.USERS(user_id),
  CONSTRAINT FK_SUPPORT_REQUESTS_ASSIGNED_STAFF FOREIGN KEY(assigned_staff_id) REFERENCES dbo.USERS(user_id)
 );
 CREATE INDEX IX_SUPPORT_REQUESTS_contract_id ON dbo.SUPPORT_REQUESTS(contract_id);
 CREATE INDEX IX_SUPPORT_REQUESTS_requested_by ON dbo.SUPPORT_REQUESTS(requested_by);
 CREATE INDEX IX_SUPPORT_REQUESTS_assigned_staff_id ON dbo.SUPPORT_REQUESTS(assigned_staff_id);
END;
GO
