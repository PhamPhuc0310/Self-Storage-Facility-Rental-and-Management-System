IF OBJECT_ID(N'dbo.SUPPORT_REQUEST_MESSAGES', N'U') IS NULL
BEGIN
 CREATE TABLE dbo.SUPPORT_REQUEST_MESSAGES (
  message_id UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_SUPPORT_REQUEST_MESSAGES_id DEFAULT NEWSEQUENTIALID(),
  request_id UNIQUEIDENTIFIER NOT NULL, author_id UNIQUEIDENTIFIER NOT NULL,
  message NVARCHAR(MAX) NOT NULL, created_at DATETIME2 NOT NULL CONSTRAINT DF_SUPPORT_REQUEST_MESSAGES_created_at DEFAULT SYSDATETIME(),
  CONSTRAINT PK_SUPPORT_REQUEST_MESSAGES PRIMARY KEY(message_id),
  CONSTRAINT FK_SUPPORT_REQUEST_MESSAGES_REQUEST FOREIGN KEY(request_id) REFERENCES dbo.SUPPORT_REQUESTS(request_id),
  CONSTRAINT FK_SUPPORT_REQUEST_MESSAGES_AUTHOR FOREIGN KEY(author_id) REFERENCES dbo.USERS(user_id)
 );
 CREATE INDEX IX_SUPPORT_REQUEST_MESSAGES_request_id ON dbo.SUPPORT_REQUEST_MESSAGES(request_id, created_at);
END;
GO
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name=N'IX_SUPPORT_REQUESTS_status_assignee' AND object_id=OBJECT_ID(N'dbo.SUPPORT_REQUESTS'))
 CREATE INDEX IX_SUPPORT_REQUESTS_status_assignee ON dbo.SUPPORT_REQUESTS(status, assigned_staff_id);
GO
